// Turns the raw 1-minute CSV into the 5-minute candles + VWAP series the reel draws.
// Usage: node scripts/build-data.mjs  ->  writes src/data.js
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const CSV = join(root, 'data', 'MSFT_2016-04-22_1min.csv');
const OUT = join(root, 'src', 'data.js');
const BAR_MINUTES = 5;

const [, ...lines] = readFileSync(CSV, 'utf8').trim().split('\n');
const minutes = lines
  .map((line) => {
    const [time, o, h, l, c, v] = line.split(',');
    return { time, o: +o, h: +h, l: +l, c: +c, v: +v };
  })
  // Regular session only: 09:30-15:59. The 16:00 row is the closing-auction print.
  .filter((m) => m.time < '16:00');

// VWAP = running sum(typical price x volume) / running sum(volume), reset each day.
let pv = 0;
let vol = 0;
const vwap1m = minutes.map((m) => {
  pv += ((m.h + m.l + m.c) / 3) * m.v;
  vol += m.v;
  return pv / vol;
});

const bars = [];
for (let i = 0; i < minutes.length; i += BAR_MINUTES) {
  const chunk = minutes.slice(i, i + BAR_MINUTES);
  bars.push({
    t: chunk[0].time,
    o: chunk[0].o,
    h: Math.max(...chunk.map((m) => m.h)),
    l: Math.min(...chunk.map((m) => m.l)),
    c: chunk[chunk.length - 1].c,
    v: chunk.reduce((s, m) => s + m.v, 0),
    vwap: vwap1m[i + chunk.length - 1],
  });
}

const round = (x, d = 4) => Math.round(x * 10 ** d) / 10 ** d;
const data = {
  ticker: 'MSFT',
  name: 'Microsoft',
  date: '2016-04-22',
  barMinutes: BAR_MINUTES,
  bars: bars.map((b) => ({ ...b, o: round(b.o), h: round(b.h), l: round(b.l), c: round(b.c), vwap: round(b.vwap) })),
  vwap1m: vwap1m.map((x) => round(x)),
};

writeFileSync(
  OUT,
  `// Generated by scripts/build-data.mjs from data/MSFT_2016-04-22_1min.csv. Do not edit by hand.\n` +
    `window.REEL_DATA = ${JSON.stringify(data)};\n`,
);
console.log(`wrote ${OUT}: ${bars.length} bars, VWAP close ${vwap1m.at(-1).toFixed(3)}`);
