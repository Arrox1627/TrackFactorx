// Turns a 1-minute CSV into the 5-minute candles, VWAP series, key moments and chart ranges the reel draws.
// Usage: node scripts/build-data.mjs [sample|msft]  ->  writes src/data.js   (default: sample)
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(root, 'src', 'data.js');
const BAR_MINUTES = 5;

const PRESETS = {
  // Made-up but realistic day from scripts/generate-sample.mjs (fictional ticker).
  sample: { csv: 'sample_1min.csv', ticker: 'DEMO', name: 'Sample stock', session: 'intraday', credit: 'Illustrative data' },
  // Real Microsoft session (see data/README.md).
  msft: { csv: 'MSFT_2016-04-22_1min.csv', ticker: 'MSFT', name: 'Microsoft', session: 'Apr 22, 2016', credit: 'Real MSFT data · Apr 22, 2016' },
};

const presetName = process.argv[2] ?? 'sample';
const preset = PRESETS[presetName];
if (!preset) throw new Error(`unknown preset "${presetName}" (use: ${Object.keys(PRESETS).join(', ')})`);

const [, ...lines] = readFileSync(join(root, 'data', preset.csv), 'utf8').trim().split('\n');
const minutes = lines
  .map((line) => {
    const [time, o, h, l, c, v] = line.split(',');
    return { time, o: +o, h: +h, l: +l, c: +c, v: +v };
  })
  // Regular session only: 09:30-15:59. A 16:00 row, if present, is the closing-auction print.
  .filter((m) => m.time < '16:00');

// VWAP = running sum(typical price x volume) / running sum(volume), reset each day.
let pv = 0;
let vol = 0;
const vwap1m = minutes.map((m) => {
  pv += ((m.h + m.l + m.c) / 3) * m.v;
  vol += m.v;
  return pv / vol;
});

const bars = [];
for (let i = 0; i < minutes.length; i += BAR_MINUTES) {
  const chunk = minutes.slice(i, i + BAR_MINUTES);
  bars.push({
    t: chunk[0].time,
    o: chunk[0].o,
    h: Math.max(...chunk.map((m) => m.h)),
    l: Math.min(...chunk.map((m) => m.l)),
    c: chunk[chunk.length - 1].c,
    v: chunk.reduce((s, m) => s + m.v, 0),
    vwap: vwap1m[i + chunk.length - 1],
  });
}

// ---- key moments the reel points at
const above = bars.map((b) => b.c > b.vwap);
const runOf = (from, want) => {
  let n = 0;
  while (from + n < bars.length && above[from + n] === want) n++;
  return n;
};
// Reclaim: first close back above VWAP after 6+ bars below, that then holds for 6+ bars.
const reclaim = bars.findIndex((_, i) => i >= 6 && above[i] && above.slice(i - 6, i).every((a) => !a) && runOf(i, true) >= 6);
if (reclaim < 0) throw new Error('no VWAP reclaim found in this session');

// Touches: after the reclaim, pullbacks whose low tags VWAP while the bar still closes above it.
// Neighbouring candidates form one pullback; keep its deepest bar.
const tol = bars[0].c * 0.0003;
const candidates = bars
  .map((b, i) => ({ i, gap: b.l - b.vwap, ok: i > reclaim + 4 && b.l <= b.vwap + tol && b.c > b.vwap }))
  .filter((x) => x.ok);
const clusters = [];
for (const x of candidates) {
  const last = clusters.at(-1);
  if (last && x.i - last.at(-1).i <= 3) last.push(x);
  else clusters.push([x]);
}
const touches = clusters.slice(0, 2).map((c) => c.reduce((a, b) => (b.gap < a.gap ? b : a)).i);
if (touches.length < 2) throw new Error('need two VWAP touches after the reclaim');

// Bounce: the highest high in the hour (12 bars) after the last touch.
let bounceHigh = touches.at(-1) + 1;
for (let i = bounceHigh; i <= Math.min(bars.length - 1, touches.at(-1) + 12); i++) if (bars[i].h > bars[bounceHigh].h) bounceHigh = i;

// ---- chart ranges: the whole day, and a close-up on the touches + bounce
const pad = (lo, hi, below, aboveFrac) => [lo - (hi - lo) * below, hi + (hi - lo) * aboveFrac];
const full = [-0.6, bars.length + 0.6, ...pad(Math.min(...bars.map((b) => b.l)), Math.max(...bars.map((b) => b.h)), 0.08, 0.08)];
const z0 = Math.max(reclaim + 1, touches[0] - 14);
const z1 = Math.min(bars.length, bounceHigh + 6);
const win = bars.slice(z0, z1);
const zoom = [z0 - 0.4, z1 + 0.4, ...pad(Math.min(...win.map((b) => Math.min(b.l, b.vwap))), Math.max(...win.map((b) => b.h)), 0.18, 0.2)];

const round = (x, d = 4) => Math.round(x * 10 ** d) / 10 ** d;
const data = {
  preset: presetName,
  ticker: preset.ticker,
  name: preset.name,
  session: preset.session,
  credit: preset.credit,
  barMinutes: BAR_MINUTES,
  bars: bars.map((b) => ({ ...b, o: round(b.o), h: round(b.h), l: round(b.l), c: round(b.c), vwap: round(b.vwap) })),
  vwap1m: vwap1m.map((x) => round(x)),
  moments: { reclaim, touches, bounceHigh },
  view: { full: full.map((x) => round(x)), zoom: zoom.map((x) => round(x)) },
};

writeFileSync(
  OUT,
  `// Generated by scripts/build-data.mjs (${presetName}) from data/${preset.csv}. Do not edit by hand.\n` +
    `window.REEL_DATA = ${JSON.stringify(data)};\n`,
);
console.log(
  `wrote ${OUT} [${presetName}]: ${bars.length} bars, reclaim ${bars[reclaim].t}, ` +
    `touches ${touches.map((i) => bars[i].t).join(' & ')}, bounce high ${bars[bounceHigh].t} ${bars[bounceHigh].h.toFixed(2)}`,
);
